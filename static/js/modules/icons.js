/**
 * 获取图标 HTML
 * @param {string} name - 图标名称（如 'trash', 'eye'）
 * @param {string} className - 额外的 CSS 类名
 * @returns {string} SVG 图标 HTML
 */
export function icon(name, className = '') {
    if (!Icons[name]) {
        console.warn(`Icon not found: ${name}`);
        return '';
    }
    
    if (className) {
        // 替换默认类名
        return Icons[name].replace('class="inline-block', `class="inline-block ${className}`);
    }
    
    return Icons[name];
}

